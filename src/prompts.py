def scripted_questions(slot: str) -> list:
    """Список вопросов слота (fallback, если LLM недоступен). Копия, не ссылка."""
    key = str(slot or "").strip().lower()
    return list(_QUESTIONS.get(key, _FALLBACK_QUESTIONS))


def slot_label(slot: str) -> str:
    """Человекочитаемое название слота; неизвестный возвращаем как есть."""
    key = str(slot or "").strip().lower()
    return SLOT_LABELS.get(key, key or "разговор")


