def parse_messages(slot: str, question: str, answer: str) -> list:
    """Messages для LLM: вернуть строго JSON {category,title,text,metrics}.

    Few-shot-примеры подаются как обычные ходы диалога — так модель точнее
    держит формат, чем при чтении инструкции.
    """
    question_text = question if isinstance(question, str) else str(question or "")
    answer_text = answer if isinstance(answer, str) else str(answer or "")
    messages = [{
        "role": "system",
        "content": system_prompt() + "\n\n" + _EXTRACTION_RULES,
    }]
    for example_question, example_entry in _PARSE_EXAMPLES:
        messages.append({"role": "user", "content": example_question})
        messages.append({
            "role": "assistant",
            "content": json.dumps(example_entry, ensure_ascii=False),
        })
    messages.append({
        "role": "user",
        "content": (
            "Слот: {slot}.\n"
            "Вопрос, который я задал: «{question}»\n"
            "Ответ человека: «{answer}»\n"
            "Верни только JSON."
        ).format(slot=slot_label(slot), question=question_text.strip(),
                 answer=answer_text.strip()),
    })
    return messages


