def _short_value(value) -> str:
    """Компактное человекочитаемое представление значения статистики."""
    try:
        if isinstance(value, bool):
            return "да" if value else "нет"
        if isinstance(value, float):
            return ("%.2f" % value).rstrip("0").rstrip(".")
        if isinstance(value, (int, str)):
            text = str(value)
            return text[:200]
        if isinstance(value, (list, tuple)):
            parts = []
            for item in list(value)[:12]:
                if isinstance(item, dict):
                    parts.append(_short_value(item))
                else:
                    parts.append(str(item))
            suffix = "" if len(value) <= 12 else " и ещё %d" % (len(value) - 12)
            return ", ".join(parts) + suffix
        if isinstance(value, dict):
            return json.dumps(value, ensure_ascii=False, default=str)[:300]
        return str(value)[:200]
    except Exception:
        return "?"


def _format_stats(stats) -> str:
    """Статистика → строки «- подпись: значение». Терпимо к любой форме."""
    if isinstance(stats, dict) and stats:
        lines = []
        for key, value in stats.items():
            label = _STATS_LABELS.get(str(key), str(key))
            lines.append("- %s: %s" % (label, _short_value(value)))
        return "\n".join(lines)
    if stats in (None, {}, [], ""):
        return "- данных за неделю почти нет: записей мало или они пустые"
    return "- " + _short_value(stats)


def weekly_prompt(stats: dict) -> str:
    """User-промпт для LLM: короткий недельный дайджест по статистике.

    Используется так:
        llm.chat([{"role": "system", "content": system_prompt()},
                  {"role": "user", "content": weekly_prompt(stats)}])
    """
    return (
        "Ниже — данные за неделю. Напиши по ним короткий живой итог недели "
        "для человека.\n\n"
        "Данные:\n{stats}\n\n"
        "Как писать:\n"
        "- 3–5 предложений, по-русски, тёпло и по делу, без лести и морали.\n"
        "- Начни с одной главной вещи, которую видно по данным.\n"
        "- Отметь 1–2 удачи и 1 слабое место — мягко, фактами, без «надо».\n"
        "- В конце — один вопрос: что важно на следующую неделю.\n"
        "- Не выдумывай цифр, которых нет в данных, и не перечисляй всё подряд.\n"
        "- Верни только текст итога, без заголовков и списков."
    ).format(stats=_format_stats(stats))


