_FOLLOWUP_RULES = """Сейчас у тебя одна задача — понять, нужен ли к ответу человека один уточняющий вопрос.

Правила:
- Если ответ уже достаточно подробный — есть что, сколько, когда, как именно, названия или цифры — ответь ровно: OK
- Если ответ общий и непонятны важные детали — задай ОДИН короткий уточняющий вопрос по сути ответа.
- Если вопрос вообще не требует деталей (например, «как настроение?») и человек ответил осмысленно — просто ответь OK.
- Уточнение — только вопрос. Без «Спасибо», «Понял», «Расскажи подробнее», без оценок, советов и предисловий.
- Не повторяй исходный вопрос. Не спрашивай то, что человек уже сказал. Не задавай больше одного вопроса.
- Если человек явно отказывается уточнять («не хочу», «неважно», «пропусти») — ответь OK.
- Ответ строго один из двух: «OK» или текст вопроса. Ничего больше."""

_HISTORY_IN_DIRECTIONS = {"in", "user", "incoming", "u", "client", "user_in"}


def _history_to_messages(history, answer: str) -> list:
    """История диалога → сообщения чата.

    Принимаем два формата, чтобы не зависеть от того, кто зовёт:
    * OpenAI-сообщения: {"role": "user"|"assistant", "content": "..."}
      (так историю отдаёт scheduler._llm_history());
    * строки из storage.chat_history(): {"direction": "in"|"out", "text": "..."}.
    Всё остальное молча пропускаем. Терпимо к мусору.
    """
    messages = []
    if not isinstance(history, (list, tuple)):
        return messages
    answer_norm = (answer or "").strip()
    for raw in list(history)[-12:]:
        if not isinstance(raw, dict):
            continue
        role = None
        content = ""
        # формат OpenAI chat messages
        raw_role = str(raw.get("role", "")).strip().lower()
        raw_content = raw.get("content")
        if raw_role in ("user", "assistant") and isinstance(raw_content, str) \
                and raw_content.strip():
            role = raw_role
            content = raw_content.strip()
        else:
            # формат storage.chat_history
            raw_text = raw.get("text")
            if isinstance(raw_text, str) and raw_text.strip():
                direction = str(raw.get("direction", "")).strip().lower()
                role = "user" if direction in _HISTORY_IN_DIRECTIONS else "assistant"
                content = raw_text.strip()
        if role is None or not content:
            continue
        # не дублируем текущий ответ, если бот-core уже записал его в историю
        if role == "user" and content == answer_norm:
            continue
        messages.append({"role": role, "content": content})
    # история должна начинаться с пользователя — иначе некоторые модели капризничают
    while messages and messages[0]["role"] != "user":
        messages.pop(0)
    return messages


def followup_messages(slot: str, question: str, answer: str,
                      history: list) -> list:
    """Messages для LLM: ответ — «OK» (уточнение не нужно) или текст вопроса."""
    question_text = question if isinstance(question, str) else str(question or "")
    answer_text = answer if isinstance(answer, str) else str(answer or "")
    system = system_prompt() + "\n\n" + _FOLLOWUP_RULES
    messages = [{"role": "system", "content": system}]
    messages.extend(_history_to_messages(history, answer_text))
    messages.append({
        "role": "user",
        "content": (
            "Слот: {slot}.\n"
            "Вопрос, который я задал: «{question}»\n"
            "Ответ человека: «{answer}»\n\n"
            "Нужен ли уточняющий вопрос? Ответь ровно OK, если ответ достаточно "
            "подробный, иначе — одним коротким вопросом."
        ).format(
            slot=slot_label(slot),
            question=question_text.strip(),
            answer=answer_text.strip(),
        ),
    })
    return messages


def followup_is_skip(reply: str) -> bool:
    """True, если модель ответила OK (уточнение не нужно).

    Не входит в обязательный контракт, но избавляет bot-core от ручного разбора.
    Строго точное OK/ОК (с точкой/кавычками по краям), без префиксов: иначе
    «Окей, а сколько воды выпил?» считалось бы «уточнение не нужно» и терялось.
    """
    if not isinstance(reply, str):
        return False
    clean = reply.strip().strip(".!\"'«» ").upper()
    return clean in ("OK", "ОК")


